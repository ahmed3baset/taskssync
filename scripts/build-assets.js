'use strict';

const fs = require('node:fs');
const path = require('node:path');

const PUBLIC_DIR = path.join(__dirname, '..', 'public');
const OUT_FILE = path.join(__dirname, '..', 'assets.generated.js');

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.webmanifest': 'application/manifest+json; charset=utf-8',
  '.png': 'image/png',
  '.svg': 'image/svg+xml',
  '.ico': 'image/x-icon',
};

const files = {};
function walk(dir, prefix = '') {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    const url = `${prefix}/${entry.name}`;
    if (entry.isDirectory()) walk(full, url);
    else files[url] = fs.readFileSync(full);
  }
}
walk(PUBLIC_DIR);

const entries = Object.entries(files).map(
  ([url, buffer]) =>
    `  ${JSON.stringify(url)}: { type: ${JSON.stringify(
      TYPES[path.extname(url)] || 'application/octet-stream'
    )}, body: ${JSON.stringify(buffer.toString('base64'))} }`
);

const output = `// Generated by scripts/build-assets.js — do not edit by hand.\nexport const assets = {\n${entries.join(',\n')}\n};\n`;
fs.writeFileSync(OUT_FILE, output, 'utf8');
console.log(`Bundled ${entries.length} static files into assets.generated.js`);
